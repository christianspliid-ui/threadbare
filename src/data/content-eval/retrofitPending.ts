/**
 * `RETROFIT_PENDING` — the Composition Contract's ratchet. THR-1045.
 *
 * Plan: `Docs/plans/2026-08-08-encounter-factory-workflow.md` §3 item 2 and
 * ruling 8 ("retrofit all 15 nudge-era encounters to the full contract").
 *
 * **What it is.** Every template id here predates the contract and is allowed to
 * fail `check:encounter` without failing CI. Everything *not* here must pass.
 *
 * **Why a named list and not a count.** A threshold ("≤ 200 failures") lets a
 * new non-compliant template hide behind a retrofitted one — the number stays
 * flat while the corpus rots sideways. A named list cannot: adding a template
 * means adding its id in a diff someone reviews, and the ratchet test refuses
 * any id that is not already here.
 *
 * **It only ever shrinks.** Deleting a name is the retrofit's proof — the id
 * leaves this file in the same commit the template becomes composition-complete,
 * and `compositionContract.test.ts` fails both ways: if a listed template now
 * passes (a stale entry is a lie about the corpus) and if an unlisted one fails.
 *
 * **This is not an exemption mechanism** (ruling 3). An exemption is per-block,
 * permanent, and authored by whoever wants to skip a rule. This is per-template,
 * temporary, and its only direction of travel is out.
 *
 * Regenerate the list — never by hand, and only ever to *remove* names:
 *   `npm run check:encounter -- --all --list-failures`
 */
