/**
 * Infer ActionScale from actor affinities.
 * faction/settlement actors operate at regional scale;
 * individual actors operate at personal scale.
 */
/**
 * Derive intrinsicTier from rarityTier per the attention model spec:
 *   1 (Mundane)  → 'background'
 *   2 (Uncommon) → 'shaping'
 *   3 (Rare)     → 'story_beat'
 *   4 (Epic)     → 'story_beat'
 */
function rarityTierToIntrinsicTier(
  rarityTier: number,
): UnifiedActionTemplate['intrinsicTier'] {
  if (rarityTier >= 3) return 'story_beat';
  if (rarityTier === 2) return 'shaping';
  return 'background';
}

function inferScaleFromActorAffinities(affinities?: string[]): ActionScale {
  if (!affinities || affinities.length === 0) return 'regional';
  if (affinities.includes('faction') || affinities.includes('settlement')) return 'regional';
  if (affinities.includes('individual')) return 'personal';
  return 'regional';
}

/**
 * Map encounterType to a CRUD classification.
 *
 * Audit 2026-04-17 (THR-90): All 10 encounter types reviewed.
 * - create/hire/build → 'create': these all establish a new entity or relationship.
 * - explore/acquire/steal/trade → 'read': these gather or extract existing value.
 *   Note: 'steal' uses 'read' (not 'delete') because the target inventory is
 *   not destroyed — value is redistributed. Future: could become 'delete' if we
 *   model per-item inventory destruction, but 'read' is correct for now.
 * - duel → 'delete': duels aim to remove a threat (defeat/kill the target).
 * - assist/lead → 'update' (default): these modify relationships or states
 *   without creating or removing entities.
 * Locked via encounterTypeToCrud-audit.test.ts as a regression gate.
 */
export function encounterTypeToCrud(
  encounterType: string,
): 'create' | 'read' | 'update' | 'delete' {
  switch (encounterType) {
    case 'create':
    case 'hire':
    case 'build':
      return 'create';
    case 'explore':
    case 'acquire':
    case 'steal':
    case 'trade':
      return 'read';
    case 'duel':
      return 'delete';
    default: // assist, lead, and any future types
      return 'update';
  }
}

/**
 * Convert an EncounterStep to an ActionStep.
 * EncounterStep difficulty is on 0–100 scale; ActionStep uses 0–1.
 *
 * Important: this migration only carries consequence fields with a clean
 * unified-runtime consumer today. Anything richer belongs in the encounter
 * migration audit/ledger until the supporting primitive exists.
 */
function migrateEncounterOutcomeMetadata(outcome: EncounterOutcome): ActionStepOutcomeMetadata | undefined {
  if (
    outcome.rewardPool === undefined &&
    outcome.tierPromotionEligible === undefined &&
    outcome.reputationDelta === undefined
  ) {
    return undefined;
  }

  return {
    rewardPool: outcome.rewardPool,
    tierPromotionEligible: outcome.tierPromotionEligible,
    reputationDelta: outcome.reputationDelta,
  };
}

function inferEncounterFailBehavior(
  template: EncounterTemplate,
  stepIndex: number,
): ActionStep['failBehavior'] {
  // Phase 5: migrated encounters should fail forward by default on early steps.
  // The final step still hard-stops unless/until we author a more specific
  // consequence contract for that encounter.
  return stepIndex < template.steps.length - 1 ? 'continue_weakened' : 'fail_action';
}

function migrateEncounterStep(
  template: EncounterTemplate,
  step: EncounterStep,
  stepIndex: number,
): ActionStep {
  const duration = step.duration ?? 1;

  return {
    reach: step.reach,
    duration: { min: duration, max: duration },
    difficulty: step.difficulty / 100,
    onSuccess: [],
    onFailure: [],
    failBehavior: inferEncounterFailBehavior(template, stepIndex),
    narrativeTemplate: step.narrative,
    successMetadata: migrateEncounterOutcomeMetadata(step.onSuccess),
    failureMetadata: migrateEncounterOutcomeMetadata(step.onFailure),
  };
}

/**
 * Convert an old ActionTemplateData (1-step CRUD action) to a UnifiedActionTemplate.
 */
export function migrateActionTemplate(old: ActionTemplateData): UnifiedActionTemplate {
  const affinities = old.actorAffinities as ActorType[] | undefined;
  const scale = inferScaleFromActorAffinities(old.actorAffinities);

  return {
    id: old.id,
    name: old.name,
    reach: old.reach,
    crudType: old.crudType,
    scale,
    steps: [
      {
        reach: old.reach,
        duration: { min: old.durationRange.min, max: old.durationRange.max },
        difficulty: old.difficulty,
        onSuccess: old.onSuccess,
        onFailure: old.onFailure,
        failBehavior: 'fail_action',
      },
    ],
    apCost: 1,
    actorAffinities: affinities ?? ['individual', 'faction'],
    locationSubtypes: old.locationSubtypes,
    sphereAffinity: old.sphereAffinity as UnifiedActionTemplate['sphereAffinity'],
    motivations: old.motivations,
    narrativeTemplates: {
      initiation: old.narrativeTemplates.initiation,
      success: old.narrativeTemplates.success,
      failure: old.narrativeTemplates.failure,
    },
    // Phase 17: pass through display fields
    spellName: old.spellName,
    description: old.description,
    // TB-100: pass through rarity tier (default 1 if not set)
    rarityTier: old.rarityTier ?? 1,
    // Single-step CRUD actions are always background regardless of rarity
    intrinsicTier: 'background',
  };
}

/**
 * Convert an EncounterTemplate (multi-step) to a UnifiedActionTemplate.
 */
export function migrateEncounterTemplate(old: EncounterTemplate): UnifiedActionTemplate {
  const crudType = encounterTypeToCrud(old.encounterType);
  const motivations = ENCOUNTER_TYPE_MOTIVATIONS[old.encounterType] ?? old.motivations;

  // Use first step for initiation narrative, last step for success/failure
  const firstStep = old.steps[0];
  const lastStep = old.steps[old.steps.length - 1];

  return {
    id: old.id,
    name: old.name,
    reach: old.reachPrimary,
    crudType,
    scale: 'local',
    steps: old.steps.map((step, index) => migrateEncounterStep(old, step, index)),
    apCost: 1,
    actorAffinities: ['individual'],
    locationSubtypes: [
      ...old.locationTypes,
      ...(old.sublocationTypes ?? []),
    ],
    sphereAffinity: old.sphereAffinity,
    motivations,
    narrativeTemplates: {
      initiation: firstStep?.narrative ?? `${old.name} begins.`,
      success: lastStep?.onSuccess.narrative ?? `${old.name} succeeds.`,
      failure: lastStep?.onFailure.narrative ?? `${old.name} fails.`,
    },
    supportBundle: old.supportBundle,
    clearanceGates: old.clearanceGates,
    // TB-100: encounter templates default to tier 1 (Mundane); derive intrinsicTier from rarity
    rarityTier: 1,
    intrinsicTier: rarityTierToIntrinsicTier(1),
  };
}

function buildCanonicalEncounterTemplates(): EncounterTemplate[] {
  const deduped = new Map<string, EncounterTemplate>();

  const addTemplates = (templates: readonly EncounterTemplate[]): void => {
    for (const template of templates) {
      deduped.set(template.id, template);
    }
  };

  addTemplates(ENCOUNTER_TEMPLATES);
  addTemplates(ANOMALY_ENCOUNTER_TEMPLATES);
  addTemplates(SOCIAL_ENCOUNTER_TEMPLATES);
  addTemplates(MONSTER_ENCOUNTER_TEMPLATES);

  for (const id of FACTION_ENCOUNTER_META.keys()) {
    const template = getFactionEncounterById(id);
    if (template) {
      deduped.set(template.id, template);
    }
  }

  for (const id of ARMY_ENCOUNTER_META.keys()) {
    const template = getArmyEncounterById(id);
    if (template) {
      deduped.set(template.id, template);
    }
  }

  return [...deduped.values()];
}

